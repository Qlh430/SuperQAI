"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const source = path.join(__dirname, "design-sources");
const runtime = path.resolve(__dirname, "../AI-OS-Portable-1.0.5-win-x64/.ai-runtime/versions/1.0.5-win-x64/resources/app");
const temp = fs.mkdtempSync(path.join(os.tmpdir(), "neon-curated-test-"));
for (const name of ["system-db.js", "resource-access.js", "resource-http-api.js", "auth-crypto.js", "asset-library-service.js", "project-share-access.js", "curated-asset-service.js", "curated-asset-http-api.js", "canvas-media-lifecycle.js", "canvas-media-references.js"]) {
  const file = fs.existsSync(path.join(source,name)) ? path.join(source,name) : path.resolve(__dirname,"../host-sources/app",name);
  if (fs.existsSync(file)) fs.copyFileSync(file,path.join(temp,name));
}
const { createSystemDb } = require(path.join(temp,"system-db.js"));
const db = createSystemDb({dbPath:path.join(temp,"test.sqlite")});
db.migrate();
async function main() {
  assert.equal(typeof db.listCuratedAssets, "function", "显式素材库独立于自动媒体注册");
  for (const id of ["owner","reader","other","disabled"]) db.insertUser({id,username:id,displayName:id,role:"user",status:id === "disabled" ? "disabled" : "active",passwordHash:"test"});
  const { createResourceAccess } = require(path.join(temp,"resource-access.js"));
  const access = createResourceAccess({db});
  const { createAssetLibraryService } = require(path.join(temp,"asset-library-service.js"));
  const automatic = createAssetLibraryService({db,resourceAccess:access,projectService:{requireOwnerProject(){throw new Error("unexpected project access");}}});
  const media = await automatic.registerMedia("owner",{url:"/output/original%20image.png",filename:"原图"},"image/png");
  const originalId = media.id;
  await assert.rejects(()=>access.registerResource({type:"image",ownerUserId:"reader",title:"伪造媒体",refType:"output_media",refId:"/output/original image.png"}),e=>e.code==="forbidden");
  assert.equal(db.listCuratedAssets().length,0,"自动注册不得自动入库");
  assert.ok(fs.existsSync(path.join(temp,"curated-asset-service.js")),"素材库服务显式管理条目");
  const { createCuratedAssetService } = require(path.join(temp,"curated-asset-service.js"));
  const library = createCuratedAssetService({db,resourceAccess:access});
  assert.deepEqual((await library.list("owner")).entries,[]);
  assert.deepEqual((await library.list("owner")).categories.map(x=>x.id),["roles","scenes","props","other"]);
  const first = await library.add("owner",{resourceId:originalId,name:"角色甲",categoryId:"roles"});
  assert.equal(first.entry.resource.id,originalId);
  assert.equal(first.entry.resource.metadata.url,"/output/original%20image.png");
  assert.equal(first.entry.resource.title,"角色甲");
  assert.equal(db.getResource(originalId).title,"角色甲");
  const duplicate = await library.add("owner",{media:{url:"/output/original%20image.png",kind:"image"},name:"其他名字",categoryId:"props"});
  assert.equal(duplicate.duplicate,true);
  assert.equal(duplicate.entry.asset.id,first.entry.asset.id);
  assert.equal(duplicate.entry.resource.title,"其他名字");
  assert.equal(duplicate.entry.asset.categoryId,"props");
  assert.equal(db.listCuratedAssets().length,1);
  await assert.rejects(()=>library.add("reader",{resourceId:originalId,name:"未授权"}),e=>e.code==="forbidden");
  for (const url of ["https://example.com/img.png","data:image/png;base64,abc","file:///x.png","/output/../private.png","/output/%2e%2e%2fprivate.png","/output/missing.png"]) await assert.rejects(()=>library.add("owner",{media:{url,kind:"image"},name:"不安全"}));
  await library.share("owner",first.entry.asset.id,{visibility:"users",userIds:["reader"]});
  assert.equal((await library.list("reader",{scope:"shared"})).entries.length,1);
  assert.equal((await access.assertRead("reader",originalId)).permission,"read");
  assert.equal((await library.list("reader",{scope:"shared"})).entries[0].access.capabilities.share,false);
  await assert.rejects(()=>library.share("reader",first.entry.asset.id,{visibility:"all"}),e=>e.code==="forbidden");
  await assert.rejects(()=>library.share("owner",first.entry.asset.id,{visibility:"users",userIds:["disabled"]}),e=>e.code==="invalid_share_member");
  await assert.rejects(()=>access.assertRead("other",originalId),e=>e.code==="forbidden");
  const referenced = await library.add("reader",{resourceId:originalId,name:"我的引用",categoryId:"props"});
  assert.equal(referenced.entry.resource.id,originalId);
  assert.equal(referenced.entry.asset.ownerUserId,"reader");
  await library.share("owner",first.entry.asset.id,{visibility:"private"});
  assert.equal((await access.assertRead("reader",originalId)).permission,"read","明确加入素材库后保留已有引用");
  const folder = await library.createFolder("owner",{name:"人物",categoryId:"roles"});
  await library.update("owner",first.entry.asset.id,{name:"改名",categoryId:"roles",folderId:folder.id});
  assert.equal((await library.list("owner")).entries[0].asset.folderId,folder.id);
  await library.deleteFolder("owner",folder.id);
  assert.equal((await library.list("owner")).entries[0].asset.folderId,null);
  const category = await library.createCategory("owner",{name:"自定义"});
  await library.update("owner",first.entry.asset.id,{categoryId:category.id});
  await library.deleteCategory("owner",category.id);
  assert.equal((await library.list("owner")).entries[0].asset.categoryId,"other");
  await assert.rejects(()=>library.deleteCategory("owner","other"),e=>e.code==="protected_category");
  await library.hideHistory("owner",originalId);
  await library.hideHistoryMedia("owner",{media:{url:"/output/original%20image.png",kind:"image"}});
  assert.deepEqual(db.getResource(originalId).metadata.historyHiddenFor,["owner"]);
  assert.equal(db.getResource(originalId).deletedAt,null);
  await library.remove("owner",first.entry.asset.id);
  assert.equal((await library.list("owner")).entries.length,0);
  assert.equal(db.getResource(originalId).deletedAt,null);
  await access.deleteResource("owner",originalId);
  assert.equal(db.getResource(originalId).deletedAt,null,"删除历史不应让画布或素材库引用失效");
  assert.equal((await access.assertRead("reader",originalId)).permission,"read");
  const migrationResource = await automatic.registerMedia("owner",{url:"/output/shared.png",filename:"旧共享素材"},"image/png");
  await access.createShare("owner",migrationResource.id,{visibility:"all",permission:"read"});
  db.setSetting("curated_assets_shared_migration_v1",null);
  const migrated = createCuratedAssetService({db,resourceAccess:access});
  const publicList = await migrated.list("other",{scope:"public"});
  assert.equal(publicList.entries.length,1);
  assert.equal(publicList.entries[0].resource.id,migrationResource.id);
  await migrated.remove("owner",publicList.entries[0].asset.id);
  await assert.rejects(()=>access.assertRead("other",migrationResource.id),e=>e.code==="forbidden","迁移后的条目移除会撤销旧素材公开读取");
  createCuratedAssetService({db,resourceAccess:access});
  assert.equal(db.listCuratedAssets().filter(x=>x.resourceId===migrationResource.id).length,0,"迁移不得恢复用户已移除的条目");
  assert.ok(fs.existsSync(path.join(temp,"curated-asset-http-api.js")),"素材库具备独立 HTTP 路由");
  const { createCuratedAssetHttpApi } = require(path.join(temp,"curated-asset-http-api.js"));
  const http = createCuratedAssetHttpApi({curatedAssets:library,readJson:async req=>req.body,sendJson:(res,status,body)=>Object.assign(res,{status,body})});
  const request = async (method,url,body,userId="owner") => { const res={}; assert.equal(await http.handle({method,url,headers:{host:"localhost"},auth:userId?{user:{id:userId}}:null,body},res),true); return res; };
  assert.equal((await request("GET","/api/asset-library",null,null)).status,401);
  const batch = await request("POST","/api/asset-library",{items:[{resourceId:originalId,name:"恢复引用"},{resourceId:originalId,name:"重复引用"}]});
  assert.equal(batch.status,201); assert.equal(batch.body.entries.length,2); assert.equal(batch.body.duplicateCount,1);
  const badBatch = await request("POST","/api/asset-library",{items:[{resourceId:migrationResource.id,name:"有效"},{media:{url:"/output/nonexistent.png",kind:"image"},name:"无效"}]});
  assert.equal(badBatch.status,404);
  assert.equal(db.listCuratedAssets().some(x=>x.resourceId===migrationResource.id),false,"批量添加遇到无效条目不得部分保存");
  assert.equal((await request("GET","/api/asset-library?scope=mine&search=重复")).body.entries.length,1);
  const assetId = batch.body.entry.asset.id;
  assert.equal((await request("PATCH",`/api/asset-library/${assetId}/share`,{visibility:"all"})).status,200);
  assert.equal((await request("GET","/api/asset-library?scope=public",null,"other")).body.entries.length,1);
  assert.equal((await request("PATCH",`/api/asset-library/${assetId}`,{name:"修改名称"},"reader")).status,403);
  const madeCategory = await request("POST","/api/asset-library/categories",{name:"表情"});
  assert.equal(madeCategory.status,201); assert.equal(madeCategory.body.category.name,"表情");
  const madeFolder = await request("POST","/api/asset-library/folders",{name:"开心",categoryId:madeCategory.body.category.id});
  assert.equal(madeFolder.status,201);
  assert.equal((await request("GET","/api/asset-library/categories")).body.categories.length,5);
  assert.equal((await request("PATCH",`/api/asset-library/folders/${madeFolder.body.folder.id}`,{parentId:madeFolder.body.folder.id})).status,400);
  assert.equal((await request("DELETE",`/api/asset-library/history/${originalId}`,null,"reader")).status,403);
  assert.equal((await request("DELETE",`/api/asset-library/history/${originalId}`)).body.hidden,true);
  assert.equal((await request("DELETE",`/api/asset-library/${assetId}`)).status,200);
  assert.equal((await request("GET","/api/asset-library/unknown/unsupported")).status,404);
  const { createResourceHttpApi } = require(path.join(temp,"resource-http-api.js"));
  const resourcesHttp = createResourceHttpApi({resourceAccess:access,getShareForResource:id=>db.getShareForResource(id),readJson:async req=>req.body,sendJson:(res,status,body)=>Object.assign(res,{status,body}),sendError:(res,error)=>Object.assign(res,{status:error.statusCode||500,body:{error:error.message}})});
  const ownHistory = {}; await resourcesHttp.handle({method:"GET",url:"/api/resources?scope=mine&history=1",headers:{host:"localhost"},auth:{user:{id:"owner"}}},ownHistory);
  assert.equal(ownHistory.status,200);
  assert.equal(ownHistory.body.resources.some(x=>x.resource.id===originalId),false,"已移除的个人历史不会重新出现");
  assert.ok(ownHistory.body.resources.every(x=>x.resource.ownerUserId==="owner"));
  const forged = {}; await resourcesHttp.handle({method:"POST",url:"/api/resources",headers:{host:"localhost"},auth:{user:{id:"other"}},body:{type:"image",title:"猜测文件",refType:"output_media",refId:"/output/private.png"}},forged);
  assert.equal(forged.status,403,"浏览器不得自行声明宿主媒体归属");
  assert.equal(db.getResourceByRef("output_media","/output/private.png"),null);
}
main().then(()=>console.log("curated asset regression passed")).finally(()=>{db.close();fs.rmSync(temp,{recursive:true,force:true});}).catch(error=>{console.error(error);process.exitCode=1;});
