const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
;(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe' })
  try {
    const page = await browser.newPage({ viewport: { width: 1728, height: 1050 } })
    const errors = []; page.on('pageerror', error => errors.push(error.message))
    const screenshotDir = path.join(__dirname, 'acceptance', 'connection-magnet'); fs.mkdirSync(screenshotDir, { recursive: true })
    await page.route('**/api/**', route => route.fulfill({ json: { authenticated: false, models: [], providers: [], boards: [], projects: [], resources: [], records: [], preferences: {}, settings: {} } }))
    if (process.env.GENERATOR_SOURCE || process.env.QA_RUNTIME_BASELINE) for (const name of ['script.js', 'flora-node-shell.js', 'flora-generator-composer.js', 'flora-node-shell.css', 'neon-canvas-surface.css', 'flora-connection-interaction.js', 'canvas-scene-layer.js']) {
      const file = path.join(process.env.QA_RUNTIME_BASELINE || process.env.GENERATOR_SOURCE, name === 'script.js' && !process.env.QA_RUNTIME_BASELINE ? 'script-before-save-bridge.js' : name)
      if (fs.existsSync(file)) await page.route(`**/${name}*`, route => route.fulfill({ contentType: name.endsWith('.css') ? 'text/css' : 'application/javascript', body: fs.readFileSync(file, 'utf8') }))
    }
    await page.goto(process.env.AI_OS_TEST_URL || 'http://127.0.0.1:3199/', { waitUntil: 'domcontentloaded' })
    if (process.env.GENERATOR_SOURCE && fs.existsSync(path.join(process.env.GENERATOR_SOURCE, 'flora-connection-interaction.js')) && !await page.evaluate(() => Boolean(window.FloraConnectionInteraction))) await page.addScriptTag({ path: path.join(process.env.GENERATOR_SOURCE, 'flora-connection-interaction.js') })
    await page.evaluate(async () => {
      const loaded = await AiOsModuleLoader.ensure(['canvas-runtime', 'canvas-node-text', 'canvas-node-media', 'canvas-node-asset-collection'])
      if (loaded?.ok === false) throw new Error(JSON.stringify(loaded))
      await loadCanvasBoards(); canvasState.activeBoardId = 'qa-magnet'
      const surface = document.createElement('div'); surface.id = 'neonEngineSurface'
      surface.style.cssText = 'position:fixed;inset:0;z-index:2147483000;display:flex;flex-direction:column;background:#080a0e'
      const view = document.querySelector('#canvasView'); surface.append(view); document.body.append(surface)
      view.hidden = false; view.classList.add('active'); view.style.cssText = 'flex:1;min-height:0;width:100%'
      document.querySelector('#canvasEditorScreen').hidden = false; document.body.classList.add('canvas-surface-open'); showCanvasEditor()
      window.qaSource = addCanvasUploadPlaceholder({ x: 40, y: 60 })
      renderCanvasUploadNode(qaSource, { src: 'data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aJ1sAAAAASUVORK5CYII=', name: '参考图' })
      window.qaTarget = addCanvasText({ x: 720, y: 60 }, { focus: false }); setCanvasTextValue(qaTarget, '连接目标正文')
      canvasState.scale = 1; canvasState.x = 140; canvasState.y = 0; applyCanvasTransformNow(); selectCanvasNode(qaSource)
    })
    const source = page.locator('.canvas-node[data-upload-only="true"] .canvas-port-output').first()
    const target = page.locator('.canvas-node-text .canvas-port-input').first()
    async function center(locator) { const b = await locator.boundingBox(); return { x: b.x + b.width / 2, y: b.y + b.height / 2 } }
    const original = await center(source)
    await page.mouse.move(original.x + 26, original.y + 8)
    await page.waitForTimeout(180)
    assert.equal(await source.evaluate(port => port.classList.contains('is-magnetized')), true, '连接点附近感应并高亮')
    const followed = await center(source)
    assert.ok(followed.x > original.x + 1 && followed.x <= original.x + 9, '连接点轻微跟随鼠标，位移有上限')
    await page.screenshot({ path: path.join(screenshotDir, 'hover-magnet.png') })
    await page.mouse.move(10, 10); await page.waitForTimeout(180)
    const reset = await center(source)
    assert.ok(Math.abs(reset.x - original.x) < 1 && Math.abs(reset.y - original.y) < 1, '离开感应范围回到原位')
    let end = await center(target)
    await page.mouse.move(original.x + 27, original.y)
    await page.mouse.down()
    await page.mouse.move(end.x - 27, end.y + 4, { steps: 8 })
    await page.waitForTimeout(80)
    assert.equal(await target.evaluate(port => port.classList.contains('is-snap-target')), true, '拖线靠近目标端口自动吸附')
    assert.equal(await page.locator('.canvas-connection-temp').evaluate(el => getComputedStyle(el).visibility), 'visible', '预览 SVG 不被缩略场景规则隐藏')
    await page.screenshot({ path: path.join(screenshotDir, 'snap-preview.png') })
    const snap = await page.evaluate(() => ({ point: canvasState.tempConnection.to, port: getCanvasPortPoint(qaTarget, 'input') }))
    assert.ok(Math.abs(snap.point.x - snap.port.x) < 1 && Math.abs(snap.point.y - snap.port.y) < 1, '预览线端点落在目标端口')
    await page.mouse.up(); await page.waitForTimeout(180)
    assert.equal(await page.evaluate(() => canvasState.connections.filter(c => c.from === qaSource.dataset.id && c.to === qaTarget.dataset.id).length), 1, '范围内松开完成连接')
    assert.equal(await page.evaluate(() => canvasState.pendingConnection), null, '拖线结束后不被 click 重新激活')
    assert.equal(await target.evaluate(port => port.classList.contains('is-snap-target')), false, '松开清除吸附状态')
    const line = page.locator('#canvasConnections .canvas-connection-path:not(.canvas-connection-temp)').first()
    const style = await line.evaluate(el => { const s = getComputedStyle(el); return { stroke: s.stroke, width: s.strokeWidth, dash: s.strokeDasharray, vector: s.vectorEffect } })
    assert.notEqual(style.dash, 'none', '已完成连接保持虚线')
    assert.equal(style.vector, 'non-scaling-stroke', '连线粗细不随画布缩放')
    assert.ok(parseFloat(style.width) >= 2, '连线有清晰的屏幕粗细')
    assert.equal(await line.evaluate(el => getComputedStyle(el).visibility), 'visible', '高亮主连线保持可见')
    await page.evaluate(() => clearCanvasSelection()); await page.waitForTimeout(80)
    const midpoint = await line.evaluate(el => { const p = el.getPointAtLength(el.getTotalLength() / 2); const s = new DOMPoint(p.x, p.y).matrixTransform(el.getScreenCTM()); return { x: s.x, y: s.y } })
    await page.mouse.move(midpoint.x, midpoint.y); await page.waitForTimeout(100)
    assert.equal(await line.evaluate(el => el.classList.contains('is-hovered')), true, '鼠标经过连接线时高亮')
    await page.mouse.move(10, 10); await page.waitForTimeout(80)
    await page.evaluate(() => disconnectCanvasNodes(qaSource.dataset.id, qaTarget.dataset.id))
    end = await center(target)
    await page.mouse.move(end.x - 27, end.y); await page.mouse.down()
    await page.mouse.move(original.x + 27, original.y, { steps: 8 }); await page.waitForTimeout(80)
    assert.equal(await source.evaluate(port => port.classList.contains('is-snap-target')), true, '从输入端反向拖线也吸附')
    await page.mouse.up(); await page.waitForTimeout(80)
    assert.equal(await page.evaluate(() => canvasState.connections.filter(c => c.from === qaSource.dataset.id && c.to === qaTarget.dataset.id).length), 1)
    await page.evaluate(() => disconnectCanvasNodes(qaSource.dataset.id, qaTarget.dataset.id))
    const output = page.locator('.canvas-node-text .canvas-port-output').first()
    const out = await center(output); await page.mouse.move(out.x, out.y); await page.mouse.down(); await page.mouse.move(out.x + 120, out.y + 30)
    await page.keyboard.press('Escape'); await page.mouse.up()
    assert.equal(await page.evaluate(() => canvasState.tempConnection), null, 'Esc取消预览连接')
    assert.equal(await page.locator('.is-snap-target').count(), 0)
    await page.evaluate(() => selectCanvasNode(qaSource))
    const blurStart = await center(source)
    await page.mouse.move(blurStart.x, blurStart.y); await page.mouse.down(); await page.mouse.move(blurStart.x + 100, blurStart.y + 50)
    await page.evaluate(() => window.dispatchEvent(new Event('blur')))
    assert.equal(await page.evaluate(() => canvasState.tempConnection), null, '窗口失焦时取消拖线')
    await page.mouse.up()
    await page.evaluate(() => { window.qaInvalid = addCanvasText({ x: 180, y: 630 }, { focus: false }); setCanvasTextValue(qaInvalid, '不兼容的文本来源') })
    const incompatible = await page.evaluate(() => {
      const port = qaInvalid.querySelector('.canvas-port-output'), rect = port.getBoundingClientRect()
      return findCanvasConnectionSnap(rect.x + rect.width / 2, rect.y + rect.height / 2, { targetNode: qaSource })?.handle || null
    })
    assert.equal(incompatible, null, '不兼容端口不吸附')
    await page.evaluate(() => { qaInvalid.remove(); window.FloraConnectionInteraction.clear() })
    const memberResult = await page.evaluate(() => {
      window.qaMulti = addCanvasAssetCollection({ x: 340, y: 40 }, { members: [
        { id: 'ref-a', kind: 'image', src: 'data:image/svg+xml,<svg xmlns="http://www.w3.org/2000/svg" width="2" height="2"/>', name: '图片一' },
        { id: 'ref-b', kind: 'image', src: 'data:image/svg+xml,<svg xmlns="http://www.w3.org/2000/svg" width="3" height="3"/>', name: '图片二' },
      ] })
      const ports = [...qaMulti.querySelectorAll('[data-canvas-port^="member-output:"]')]
      return ports.map(port => {
        const rect = port.getBoundingClientRect(), x = rect.left + rect.width / 2, y = rect.top + rect.height / 2
        const snap = findCanvasConnectionSnap(x, y, { targetNode: qaTarget })
        return { expected: port.dataset.canvasPort, actual: snap?.handle }
      })
    })
    assert.equal(memberResult.length, 2, '多成员素材节点有两个真实输出端口')
    memberResult.forEach(result => assert.equal(result.actual, result.expected, '选择最近成员端口并保留其标识'))
    await page.evaluate(() => { qaMulti.remove(); window.FloraConnectionInteraction.clear(); selectCanvasNode(qaTarget) })
    await page.evaluate(() => selectCanvasNode(qaSource))
    await source.focus()
    assert.equal(await source.evaluate(port => port === document.activeElement), true, '保留键盘聚焦端口')
    await page.screenshot({ path: path.join(screenshotDir, 'focus-port.png') })
    for (const width of [390, 768, 1440, 1728]) {
      await page.setViewportSize({ width, height: 1050 })
      for (const scale of [0.25, 0.65, 1.5]) {
        await page.evaluate(({ width, scale }) => { canvasState.scale = scale; canvasState.x = width / 2 - 450 * scale; canvasState.y = 120; applyCanvasTransformNow(); selectCanvasNode(qaSource) }, { width, scale })
        const portCenter = await center(source)
        await page.mouse.move(portCenter.x - 30, portCenter.y); await page.waitForTimeout(100)
        assert.equal(await source.evaluate(port => port.classList.contains('is-magnetized')), true, `${width}/${scale} 感应半径保持屏幕尺寸`)
        await page.mouse.move(10, 10); await page.waitForTimeout(160)
        await page.evaluate(({ width, scale }) => { canvasState.scale = scale; canvasState.x = width / 2 - 600 * scale; canvasState.y = 120; applyCanvasTransformNow(); clearCanvasSelection(); connectCanvasNodes(qaSource.dataset.id, qaTarget.dataset.id); renderCanvasConnections() }, { width, scale })
        await page.mouse.move(10, 10); await page.waitForTimeout(120)
        const wire = await line.evaluate(el => ({ vector: getComputedStyle(el).vectorEffect, stroke: getComputedStyle(el).stroke, width: parseFloat(getComputedStyle(el).strokeWidth) }))
        assert.equal(wire.vector, 'non-scaling-stroke')
        assert.ok(wire.width * scale >= 2.4 && wire.width * scale <= 3.1, `${width}/${scale} 线条抵消画布 CSS 缩放`)
        await page.screenshot({ path: path.join(screenshotDir, `${width}-${scale}-default.png`) })
        await page.evaluate(() => selectCanvasNode(qaTarget)); await page.waitForTimeout(100)
        await page.screenshot({ path: path.join(screenshotDir, `${width}-${scale}-selected.png`) })
        assert.equal(await line.evaluate(el => el.classList.contains('is-related')), true, '选中节点时相关连线高亮')
      }
    }
    assert.deepEqual(errors, [])
    console.log(JSON.stringify({ ok: true, widths: [390, 768, 1440, 1728], scales: [.25, .65, 1.5], screenshots: 27, errors }))
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
