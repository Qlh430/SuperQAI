"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const root = fs.mkdtempSync(path.join(os.tmpdir(), "neon-media-naming-"));
const source = path.join(__dirname, "design-sources");
const host = path.resolve(__dirname, "../host-sources/app");
for (const name of ["system-db", "resource-access", "auth-crypto", "project-share-access", "curated-asset-service", "canvas-media-lifecycle", "canvas-media-references"]) fs.copyFileSync(path.join(fs.existsSync(path.join(source, name + ".js")) ? source : host, name + ".js"), path.join(root, name + ".js"));
fs.copyFileSync(path.join(host, "asset-library-service.js"), path.join(root, "asset-library-service.js"));
fs.copyFileSync(path.join(source, "resource-http-api.js"), path.join(root, "resource-http-api.js"));
const { createSystemDb } = require(path.join(root, "system-db.js"));
const { createResourceAccess } = require(path.join(root, "resource-access.js"));
const { createAssetLibraryService } = require(path.join(root, "asset-library-service.js"));
const { createCuratedAssetService } = require(path.join(root, "curated-asset-service.js"));
const { generatedDisplayName: historyDisplayName } = require(path.join(root, "resource-http-api.js"));
let db;
function open() {
  db = createSystemDb({ dbPath: path.join(root, "test.sqlite") }); db.migrate();
  const access = createResourceAccess({ db });
  return { access, media: createAssetLibraryService({ db, resourceAccess: access, projectService: {} }), library: createCuratedAssetService({ db, resourceAccess: access }) };
}
(async () => {
  let { access, media, library } = open();
  for (const id of ["owner", "other", "reader", "disabled"]) db.insertUser({ id, username: id, displayName: id, role: "user", status: id === "disabled" ? "disabled" : "active", passwordHash: "test" });
  const generated = (url, kind = "image", user = "owner") => media.registerMedia(user, { url, filename: "uuid." + (kind === "image" ? "png" : kind === "video" ? "mp4" : "wav") }, kind + "/" + (kind === "image" ? "png" : kind === "video" ? "mp4" : "wav"), { source: "generated" });
  const first = await generated("/output/first.png");
  assert.equal(first.name, "image_00001", "新生成素材使用无前缀账户媒体序列");
  const results = await Promise.all(Array.from({ length: 15 }, (_, i) => generated(`/output/concurrent-${i}.png`)));
  assert.equal(new Set(results.map(item => item.name)).size, 15);
  assert.equal(results.at(-1).name, "image_00016");
  assert.equal((await generated("/output/v.mp4", "video")).name, "video_00001");
  assert.equal((await generated("/output/a.wav", "audio")).name, "audio_00001");
  assert.equal((await generated("/output/other.png", "image", "other")).name, "image_00001");
  await assert.rejects(() => generated("/output/first.png", "image", "other"), e => e.code === "forbidden");
  await assert.rejects(() => generated("/output/disabled.png", "image", "disabled"), e => e.statusCode === 401);
  const upload = await media.registerMedia("owner", { url: "/output/upload-uuid.png", filename: "upload-uuid.png" }, "image/png", { source: "upload", originalName: "产品正面.png" });
  assert.equal(upload.name, "产品正面");
  const saved = await library.add("owner", { resourceId: first.id });
  assert.equal(saved.entry.asset.name, first.name);
  await library.update("owner", saved.entry.asset.id, { name: "雪地露营" });
  assert.equal((await media.getAsset("owner", first.id)).name, "雪地露营", "素材库改名同步历史主资源");
  await generated("/output/first.png");
  assert.equal((await media.getAsset("owner", first.id)).name, "雪地露营", "重复登记不覆盖手动名称、不消耗序号");
  assert.equal((await media.getAssetByUrl("owner", "/output/first.png")).downloadName, "雪地露营.png");
  const before = db.getResource(first.id);
  await access.updateResource("owner", first.id, { title: "另一名称" });
  assert.equal((await library.list("owner")).entries[0].asset.name, "另一名称", "历史改名同步素材库");
  assert.equal(db.getResource(first.id).createdAt, before.createdAt);
  assert.equal(db.getResource(first.id).refId, before.refId);
  await library.share("owner", saved.entry.asset.id, { visibility: "users", userIds: ["reader"] });
  const readCopy = await library.add("reader", { resourceId: first.id, name: "读者别名" });
  await library.update("reader", readCopy.entry.asset.id, { name: "我的共享引用" });
  assert.equal(db.getResource(first.id).title, "另一名称", "读者只能修改自己引用的别名");
  assert.equal((await media.getAssetByUrl("reader", "/output/first.png")).downloadName, "我的共享引用.png");
  await assert.rejects(() => access.updateResource("reader", first.id, { title: "越权" }), e => e.code === "forbidden");
  await library.hideHistory("owner", first.id);
  assert.equal((await library.list("owner")).entries[0].resource.id, first.id);
  await library.remove("owner", saved.entry.asset.id);
  assert.equal(db.getResource(first.id).deletedAt, null);
  await access.deleteResource("owner", first.id);
  assert.equal((await media.getAsset("reader", first.id)).url, "/output/first.png");
  db.close(); ({ access, media, library } = open());
  assert.equal((await generated("/output/restart.png")).name, "image_00017", "重启及删除后序号不复用");
  const legacy = db.registerResource({ type: "image", ownerUserId: "owner", title: "用户旧名称", refType: "output_media", refId: "/output/old.png", metadata: { url: "/output/old.png", filename: "old.png" } });
  assert.equal((await generated("/output/old.png")).name, legacy.title, "保留旧数据名称");
  const legacyGenerated = db.registerResource({ type: "image", ownerUserId: "owner", title: "BD_image_00025", refType: "output_media", refId: "/output/legacy-generated.png", metadata: { url: "/output/legacy-generated.png", filename: "legacy-generated.png", source: "generated", generationSequence: 25, generatedName: "BD_image_00025" } });
  assert.equal((await media.getAsset("owner", legacyGenerated.id)).name, "image_00025", "旧自动名按来源标记兼容展示");
  assert.equal(db.getResource(legacyGenerated.id).title, "BD_image_00025", "兼容展示不迁移存储标题");
  assert.equal(historyDisplayName(legacyGenerated), "image_00025", "历史列表按来源标记展示兼容名称");
  assert.equal(historyDisplayName({ ...legacyGenerated, title: "用户自定义名称" }), "用户自定义名称", "历史列表保留手动名称");
  const legacyEntry = await library.add("owner", { resourceId: legacyGenerated.id });
  assert.equal(legacyEntry.entry.asset.name, "image_00025", "旧自动名资产库别名按来源标记兼容展示");
  assert.equal((await media.getAssetByUrl("owner", "/output/legacy-generated.png")).downloadName, "image_00025.png", "旧自动名下载名同步兼容");
  const customAliasResource = db.registerResource({ type: "image", ownerUserId: "owner", title: "BD_image_00026", refType: "output_media", refId: "/output/custom-alias.png", metadata: { url: "/output/custom-alias.png", filename: "custom-alias.png", source: "generated", generationSequence: 26, generatedName: "BD_image_00026" } });
  const customAlias = await library.add("owner", { resourceId: customAliasResource.id, name: "保留素材名" });
  assert.equal(customAlias.entry.asset.name, "保留素材名", "资产库手动名称不受旧自动名兼容影响");
  await access.updateResource("owner", legacyGenerated.id, { title: "用户自定义名称" });
  assert.equal((await media.getAsset("owner", legacyGenerated.id)).name, "用户自定义名称", "旧素材用户改名不被前缀兼容覆盖");
  assert.equal((await library.list("owner")).entries.find(item => item.asset.resourceId === legacyGenerated.id).asset.name, "用户自定义名称", "用户改名同步后保留资产库自定义名称");
  assert.equal((await media.getAssetByUrl("owner", "/output/legacy-generated.png")).downloadName, "用户自定义名称.png", "用户改名后的下载名保留");
  const { createImageJobManager } = require(path.join(host, "image-job-manager.js"));
  let executionOwner;
  const manager = createImageJobManager({ filePath: path.join(root, "jobs.json"), execute: async (_payload, context) => {
    executionOwner = context.ownerUserId;
    const asset = await generated("/output/background.png", "image", context.ownerUserId);
    return { status: 200, body: { saved_images: [{ url: asset.url, assetId: asset.id, name: asset.name }] } };
  } });
  const job = manager.create({ prompt: "后台生成" }, { ownerUserId: "owner" });
  await manager.start(job.id);
  assert.equal(executionOwner, "owner", "后台完成登记使用服务端保存的任务账户");
  assert.equal(manager.get(job.id).result.saved_images[0].name, "image_00018");
  assert.equal(manager.get(job.id).result.saved_images[0].assetId, db.getResourceByRef("output_media", "/output/background.png").id);
  console.log("PASS persistent per-account/type sequence, concurrency, idempotency, uploads, bidirectional owner rename, shared aliases, download identity, deletion and legacy compatibility");
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(() => { db?.close(); fs.rmSync(root, { recursive: true, force: true }); });
